import assert from 'node:assert/strict';
import {dateYear, lifeYears} from './src/years.ts';
import {fictionalDocument, updatePersonDates, personDate, parseGedcomx, serializeGedcomx, GX} from './src/gedcomx.ts';
import {addCoupleEvent, updateCoupleEventDate} from './src/gedcomx.ts';
const fact = (type, date) => ({type:`http://gedcomx.org/${type}`, date:{original:date}});
assert.equal(lifeYears([fact('Birth','1950'),fact('Death','22 NOV 2026')]), '1950-2026');
assert.equal(lifeYears([fact('Birth','1950')]), '1950-?');
assert.equal(lifeYears([fact('Death','2026')]), '?-2026');
assert.equal(lifeYears(undefined), '');
assert.equal(dateYear('BET 1950 AND 1952'), '');
assert.equal(dateYear('about 1950'), 'c. 1950');
assert.equal(dateYear('+1950-01-02'), '1950');
console.log('Year label checks passed.');
const edited = updatePersonDates(fictionalDocument, 'alex', '1950', '2026');
assert.equal(lifeYears(edited.persons[0].facts), '1950-2026');
assert.equal(fictionalDocument.persons[0].facts, undefined);
assert.equal(personDate(parseGedcomx(serializeGedcomx(edited)).persons[0], 'Death'), '2026');
edited.persons[0].facts[0].sources = [{description:'#source'}];
edited.persons[0].facts[0].date.formal = '+1950';
const revised = updatePersonDates(edited, 'alex', '1951', '');
assert.deepEqual(revised.persons[0].facts[0].sources, [{description:'#source'}]);
assert.equal(revised.persons[0].facts[0].date.formal, undefined);
assert.equal(revised.persons[0].facts[1].type, GX + 'Death');
assert.equal(revised.persons[0].facts[1].date, undefined);
edited.persons[0].facts.push(fact('Birth','1952'));
assert.throws(() => updatePersonDates(edited, 'alex', '1953', '2026'), /Multiple birth/);
assert.throws(() => parseGedcomx(JSON.stringify({...fictionalDocument, persons:[{id:'alex',facts:[{type:GX+'Birth',date:{original:1950}}]}],relationships:[]})), /Invalid facts/);
console.log('Person date editing checks passed.');
let couples = addCoupleEvent(fictionalDocument, 'couple-alex-robin', 'Marriage', '2000');
couples = addCoupleEvent(couples, 'couple-alex-robin', 'Divorce', '2010');
couples = addCoupleEvent(couples, 'couple-alex-robin', 'Marriage', '2015');
couples.relationships[0].facts[2].sources = [{description:'#source'}];
couples.relationships[0].facts[2].date.formal = '+2015';
const changed = updateCoupleEventDate(couples, 'couple-alex-robin', 2, '2016');
assert.equal(couples.relationships[0].facts[2].date.original, '2015');
assert.deepEqual(changed.relationships[0].facts.map(f => f.date.original), ['2000','2010','2016']);
assert.deepEqual(changed.relationships[0].facts[2].sources, [{description:'#source'}]);
assert.equal(changed.relationships[0].facts[2].date.formal, undefined);
assert.equal(updateCoupleEventDate(changed, 'couple-alex-robin', 1, '').relationships[0].facts[1].date, undefined);
assert.throws(() => updateCoupleEventDate(couples, 'parent-alex-casey', 0, '2000'));
assert.throws(() => updateCoupleEventDate(couples, 'couple-alex-robin', 9, '2000'));
assert.deepEqual(parseGedcomx(serializeGedcomx(changed)), changed);
